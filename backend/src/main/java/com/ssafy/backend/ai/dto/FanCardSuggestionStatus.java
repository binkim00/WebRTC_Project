package com.ssafy.backend.ai.dto;

/**
 * 팬 카드 문구 후보 중 AI 추천 부분의 준비 상태다.
 *
 * <p>자막에서 직접 고르는 후보는 통화 중 이미 저장되어 바로 내려줄 수 있지만, AI 추천은 통화가
 * 끝난 뒤 Agent가 만들기 때문에 늦거나 아예 없을 수 있다. 그래서 응답을 202로 막지 않고 이
 * 상태만 함께 내려, 팬이 AI 추천을 기다리는 동안에도 자막에서 직접 문구를 고를 수 있게 한다.
 */
public enum FanCardSuggestionStatus {

    /** Agent가 아직 생성 중이므로 잠시 뒤 다시 조회하면 추천이 채워질 수 있다. */
    GENERATING,

    /** 추천 생성이 끝났다. 고를 만한 문장이 없어 빈 목록일 수도 있다. */
    COMPLETED,

    /** 생성에 실패했거나 자막이 없어 추천을 받을 수 없다. 자막 직접 선택만 가능하다. */
    UNAVAILABLE
}
