package com.ssafy.backend.auth.dto;

/**
 * 소셜 로그인 시도의 처리 결과이며 프론트가 다음 화면을 결정하는 기준이다.
 *
 * <p>세 경우를 서로 다른 HTTP 상태로 구분하지 않고 200 응답의 필드로 구분한다.
 * 신규 가입과 기존 계정 연결은 오류가 아니라 정상적인 다음 단계이기 때문이다.
 */
public enum SocialLoginStatus {

    /** 이미 연결된 소셜 계정이라 토큰 발급까지 끝났다. 추가 화면이 필요 없다. */
    LOGIN,

    /** 연결된 계정도, 같은 이메일의 계정도 없다. 추가정보 입력 화면으로 보낸다. */
    SIGNUP_REQUIRED,

    /** 같은 이메일로 이미 가입한 계정이 있다. 비밀번호 확인 화면으로 보낸다. */
    LINK_REQUIRED
}
